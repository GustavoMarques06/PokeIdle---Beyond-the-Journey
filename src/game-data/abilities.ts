// Habilidades: efeitos passivos de combate e bônus de equipe. Cada espécie tem até duas
// habilidades comuns e uma oculta; qual vale para cada Pokémon sai do uid (ver
// `abilityIdOf` em core/pokemon.ts) ou da Cápsula/Patch de Habilidade.

import type { BonusKind } from './meta';
import type { Ailment, StatKey, TypeName } from './types';

export type SpeedWeather = 'sun' | 'rain' | 'sand';

export interface AbilityDef {
  id: string;
  name: string;
  description: string;
  /** Multiplicadores de atributo. */
  stat?: Partial<Record<StatKey, number>>;
  /** Com HP ≤ 1/3, golpes desse tipo causam mais dano. */
  lowHp?: { type: TypeName; mult: number };
  /** Golpes Normais viram deste tipo (e ganham o bônus de mesmo tipo) com +20% de dano (Aerilar, Pixilar...). */
  convertNormal?: TypeName;
  /** Cada golpe é seguido de um segundo, com esta fração do dano (Elo Parental: 0,25). */
  secondHit?: number;
  /** Golpes desse tipo causam mais dano sempre. */
  typeBoost?: { type: TypeName; mult: number };
  /** Bônus de mesmo tipo (padrão 1,5). */
  stab?: number;
  /** Golpes de poder ≤ 60 causam mais dano. */
  technician?: number;
  accuracy?: number;
  /** Multiplica a precisão de quem ataca este Pokémon (< 1 = esquiva). */
  evasion?: number;
  /** Chance extra de crítico. */
  crit?: number;
  /** Multiplicador de dano recebido por tipo de golpe (0 = imune). */
  resist?: Partial<Record<TypeName, number>>;
  /** Imune a esses tipos e recupera HP ao ser atingido por eles. */
  absorb?: TypeName[];
  /** Dano recebido de golpes super efetivos. */
  superTaken?: number;
  /** Dano recebido com HP cheio. */
  fullHpTaken?: number;
  /** Dano recebido em geral. */
  taken?: number;
  statusImmune?: Ailment[];
  /** Ao receber golpe físico, pode causar status em quem atacou. */
  contact?: { ailment: Ailment; chance: number };
  /** Ao receber golpe físico, quem atacou perde essa fração do HP máximo dele. */
  thorns?: number;
  /** Multiplica o Ataque do adversário. */
  intimidate?: number;
  /** Multiplica o próprio intervalo entre ataques (< 1 = mais rápido). */
  intervalMult?: number;
  /** Multiplica o intervalo do adversário (> 1 = deixa-o mais lento). */
  foeInterval?: number;
  /** No clima indicado, o intervalo cai à metade do bônus (×0,7). */
  weatherSpeed?: SpeedWeather;
  /** Sobrevive uma vez por luta a um golpe que o derrubaria com HP cheio. */
  sturdy?: boolean;
  /** Com um status, Ataque ×1,5 e a queimadura não enfraquece. */
  guts?: boolean;
  /** Com um status, Defesa ×1,5. */
  marvelScale?: boolean;
  /** Chance de curar o próprio status a cada ação. */
  shedSkin?: number;
  /** Devolve ao adversário o status recebido. */
  synchronize?: boolean;
  /** Envenenado, recupera esta fração do HP por ação em vez de perder. */
  poisonHeal?: number;
  /** Fração do HP recuperada a cada ação própria. */
  regen?: number;
  /** Cura extra após cada vitória. */
  healOnWin?: number;
  /** Golpes "não muito efetivos" causam o dobro. */
  tintedLens?: boolean;
  /** Ignora as habilidades defensivas do alvo. */
  moldBreaker?: boolean;
  /** Só golpes super efetivos causam dano. */
  wonderGuard?: boolean;
  /** Bônus somado à equipe quando o Pokémon está numa vaga passiva. */
  passive?: { kind: BonusKind; value: number };
}

